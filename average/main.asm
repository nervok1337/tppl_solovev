; Среднее арифметическое разностей элементов двух массивов.
; NASM, Linux x86-64, только системные вызовы (без libc).

bits 64
default rel

global _start

; Номера системных вызовов Linux x86-64.
%define SYS_READ   0
%define SYS_WRITE  1
%define SYS_OPEN   2
%define SYS_CLOSE  3
%define SYS_EXIT  60

; Максимальный допустимый размер входного файла — 64 КиБ.
; Буфер на один байт больше: этот дополнительный байт позволяет обнаружить,
; что файл не помещается в установленное ограничение.
%define BUFFER_SIZE 65536


section .data
    ; Разделитель между именем обработанного файла и результатом.
    separator       db ": "
    separator_len   equ $ - separator

    ; Сообщение об ошибке в UTF-8: ": файл испорчен\n".
    ; Русская часть задана байтами, чтобы результат не зависел от кодировки,
    ; в которой ассемблер читает исходный файл.
    broken_message  db ": ", 0xd1, 0x84, 0xd0, 0xb0, 0xd0, 0xb9, 0xd0, 0xbb
                    db 0x20, 0xd0, 0xb8, 0xd1, 0x81, 0xd0, 0xbf, 0xd0, 0xbe
                    db 0xd1, 0x80, 0xd1, 0x87, 0xd0, 0xb5, 0xd0, 0xbd, 0x0a
    broken_len      equ $ - broken_message

    ; Сообщение выводится в stderr, если имя файла не передано.
    usage_message   db "Использование: ./average <файл>", 10
    usage_len       equ $ - usage_message


section .bss
    ; Рабочие буферы.
    input_buffer    resb BUFFER_SIZE + 1
    number_buffer   resb 32

    ; Данные, которые должны сохраняться между отдельными этапами программы.
    filename_ptr    resq 1
    filename_len    resq 1
    file_descriptor resq 1
    input_length    resq 1
    first_sum       resq 1
    first_count     resq 1


section .text

; =============================================================================
; Точка входа и проверка аргументов командной строки
; =============================================================================
_start:
    ; При запуске процесса стек имеет вид:
    ; [rsp] = argc, [rsp + 8] = argv[0], [rsp + 16] = argv[1].
    ; Программа принимает ровно один пользовательский аргумент — имя файла.
    mov rax, [rsp]
    cmp rax, 2
    jne .usage

    ; Запоминаем адрес argv[1], потому что он потребуется и для открытия файла,
    ; и для вывода имени файла перед результатом или сообщением об ошибке.
    mov rax, [rsp + 16]
    mov [filename_ptr], rax

    ; Системный вызов write принимает явную длину строки. argv[1] завершается
    ; нулевым байтом, поэтому определяем длину вручную, как это делает strlen.
    mov rdi, rax
    xor rcx, rcx

; Ищет конец имени файла, двигаясь по строке до нулевого байта.
; Смысл регистров:
;   RDI — адрес начала имени файла;
;   RCX — текущая длина имени и одновременно индекс проверяемого символа.
.filename_length_loop:
    cmp byte [rdi + rcx], 0
    je .filename_length_ready
    inc rcx
    jmp .filename_length_loop

; Завершает подсчёт длины имени.
; После прошлого блока RCX хранит полную длину имени без нулевого байта,
; а RDI по-прежнему хранит адрес его начала.
.filename_length_ready:
    mov [filename_len], rcx


; =============================================================================
; Открытие и чтение входного файла
; =============================================================================

    ; open(filename, O_RDONLY, 0):
    ; RDI — адрес имени файла, RSI = 0 — только чтение, RDX = 0 — режим не нужен.
    ; При успехе RAX содержит файловый дескриптор, при ошибке — отрицательный код.
    mov rax, SYS_OPEN
    mov rdi, [filename_ptr]
    xor rsi, rsi
    xor rdx, rdx
    syscall

    test rax, rax
    js .broken
    mov [file_descriptor], rax

    ; R8 хранит суммарное количество прочитанных байтов. Один read может вернуть
    ; меньше запрошенного объёма, поэтому чтение выполняется в цикле до EOF или
    ; до заполнения input_buffer всеми BUFFER_SIZE + 1 байтами.
    xor r8, r8

; Читает очередную часть файла в свободную область буфера.
; Смысл регистров на каждом проходе:
;   R8  — общее количество байтов, уже находящихся в input_buffer;
;   RAX — после syscall количество байтов, прочитанных за этот вызов;
;   RSI — адрес свободной области, куда read запишет новые данные;
;   RDX — оставшееся свободное место в буфере;
;   RDI — файловый дескриптор открытого файла.
.read_loop:
    cmp r8, BUFFER_SIZE + 1
    je .read_ready

    ; read(file_descriptor, input_buffer + r8, оставшееся_место).
    mov rax, SYS_READ
    mov rdi, [file_descriptor]
    lea rsi, [input_buffer + r8]
    mov rdx, BUFFER_SIZE + 1
    sub rdx, r8
    syscall

    ; -EINTR означает, что системный вызов прерван сигналом: его можно повторить.
    cmp rax, -4                 ; EINTR
    je .read_loop

    ; Отрицательное значение — ошибка; ноль — достигнут конец файла.
    test rax, rax
    js .close_and_broken
    jz .read_ready

    ; Положительное значение RAX равно числу прочитанных байтов.
    add r8, rax
    jmp .read_loop

; Выполняется после достижения EOF или заполнения всего рабочего буфера.
; После прошлого блока R8 хранит полную длину загруженных данных,
; а input_buffer содержит прочитанную часть файла.
.read_ready:
    mov [input_length], r8

    ; Дальнейшая работа идёт только с буфером, поэтому файл можно закрыть сразу.
    mov rax, SYS_CLOSE
    mov rdi, [file_descriptor]
    syscall

    ; Если прочитан дополнительный байт, фактический размер файла больше 64 КиБ.
    cmp qword [input_length], BUFFER_SIZE
    ja .broken


; =============================================================================
; Поиск границ первой строки и её разбор
; =============================================================================

    ; R8 указывает на начало буфера, R9 — на позицию сразу после последнего
    ; прочитанного байта, R10 перемещается по буферу в поиске первого LF.
    lea r8, [input_buffer]
    mov r9, r8
    add r9, [input_length]
    mov r10, r8

; Ищет символ LF, который отделяет первый массив от второго.
; Смысл регистров:
;   R8  — адрес начала всего входного буфера;
;   R9  — адрес конца прочитанных данных;
;   R10 — адрес текущего проверяемого символа.
.find_first_newline:
    cmp r10, r9
    je .broken                  ; без LF невозможно отделить первую строку
    cmp byte [r10], 10
    je .first_newline_found
    inc r10
    jmp .find_first_newline

; Сохраняет найденные границы файла и подготавливает первую строку к разбору.
; После прошлого блока R10 указывает на LF после первой строки;
; R8 хранит адрес начала первой строки, R9 — адрес конца файла.
.first_newline_found:
    ; parse_line использует R8–R14 как рабочие регистры, поэтому важные адреса
    ; сохраняем отдельно: R15 — конец файла, RBX — позиция первого LF.
    mov r15, r9
    mov rbx, r10

    ; Первая строка занимает диапазон [R8, RDX). Если перед LF находится CR,
    ; исключаем его из диапазона, чтобы поддерживать окончания строк CRLF.
    mov rdx, r10
    cmp rdx, r8
    je .first_line_ready
    cmp byte [rdx - 1], 13
    jne .first_line_ready
    dec rdx

; Передаёт первую строку в parse_line.
; Смысл регистров:
;   RSI — адрес первого символа первой строки;
;   RDX — адрес сразу после её последнего значимого символа;
;   RBX — адрес разделяющего LF;
;   R15 — сохранённый адрес конца входных данных.
.first_line_ready:
    mov rsi, r8
    call parse_line
    jc .broken

    ; Сохраняем сумму и количество чисел первой строки: после разбора второй
    ; строки эти значения потребуются для проверки и вычисления результата.
    mov [first_sum], rax
    mov [first_count], rcx


; =============================================================================
; Поиск границ второй строки и её разбор
; =============================================================================

    ; Вторая строка начинается сразу после первого LF. Она может завершаться
    ; концом файла либо одним LF в самом конце файла.
    mov r9, r15
    inc rbx
    mov r8, rbx                 ; R8 — начало второй строки
    mov r11, r8

; Ищет LF во второй строке, чтобы убедиться, что после неё нет третьей строки.
; Смысл регистров:
;   R8  — адрес начала второй строки;
;   R9  — адрес конца входных данных;
;   R11 — адрес текущего проверяемого символа.
.find_second_newline:
    cmp r11, r9
    je .second_line_without_lf
    cmp byte [r11], 10
    je .second_newline_found
    inc r11
    jmp .find_second_newline

; Проверяет найденное окончание второй строки и обрабатывает возможный CRLF.
; После прошлого блока R11 указывает на LF второй строки;
; R8 хранит адрес её начала, R9 — адрес конца всех входных данных.
.second_newline_found:
    ; После завершающего LF не должно оставаться байтов: иначе во входном файле
    ; присутствует третья строка или посторонние данные.
    lea rax, [r11 + 1]
    cmp rax, r9
    jne .broken

    ; Исключаем CR перед завершающим LF при формате CRLF.
    mov rdx, r11
    cmp rdx, r8
    je .second_line_ready
    cmp byte [rdx - 1], 13
    jne .second_line_ready
    dec rdx
    jmp .second_line_ready

; Обрабатывает вариант, когда вторая строка заканчивается сразу концом файла.
; После прошлого блока R8 хранит адрес начала второй строки,
; а R9 и R11 указывают на конец входных данных.
.second_line_without_lf:
    ; Если LF отсутствует, конец строки совпадает с концом прочитанных данных.
    mov rdx, r9

; Передаёт вторую строку в parse_line и сравнивает размеры двух массивов.
; Смысл регистров:
;   RSI — адрес первого символа второй строки;
;   RDX — адрес сразу после её последнего значимого символа;
; после parse_line RAX будет хранить сумму, а RCX — количество её чисел.
.second_line_ready:
    mov rsi, r8
    call parse_line
    jc .broken

    ; Среднее разностей определено только для массивов одинаковой длины.
    cmp rcx, [first_count]
    jne .broken


; =============================================================================
; Вычисление среднего арифметического разностей
; =============================================================================

    ; Для массивов x и y одинаковой длины:
    ; average(x[i] - y[i]) = (sum(x) - sum(y)) / count.
    ; После второго parse_line: RAX = sum(y), RCX = count.
    mov rdx, [first_sum]
    sub rdx, rax
    jo .broken                  ; разность не должна выйти за границы int64

    ; CQO расширяет знаковое делимое RAX до пары RDX:RAX. IDIV выполняет
    ; знаковое целочисленное деление и округляет результат к нулю.
    mov rax, rdx
    cqo
    idiv rcx
    mov rbx, rax                ; сохраняем результат: write_all изменяет RAX


; =============================================================================
; Вывод имени файла и результата
; =============================================================================

    ; Сначала в stdout выводятся имя файла и разделитель ": ".
    mov rdi, 1
    mov rsi, [filename_ptr]
    mov rdx, [filename_len]
    call write_all
    jc .exit_error

    mov rdi, 1
    lea rsi, [separator]
    mov rdx, separator_len
    call write_all
    jc .exit_error

    ; Десятичные цифры формируются справа налево в number_buffer. Последний байт
    ; заранее занят LF, а RCX хранит текущую длину готовой строки.
    mov rax, rbx
    lea rsi, [number_buffer + 31]
    mov byte [rsi], 10
    mov rcx, 1

    ; R8B — признак отрицательного числа. Для отрицательного результата NEG
    ; формирует unsigned-модуль. Даже INT64_MIN после NEG имеет корректное
    ; беззнаковое представление 2^63, которое можно обрабатывать инструкцией DIV.
    xor r8d, r8d
    test rax, rax
    jns .absolute_value_ready
    mov r8b, 1
    neg rax

; Подготавливает делитель для перевода модуля результата в десятичную строку.
; После прошлого блока:
;   RAX — модуль выводимого результата;
;   R8B — признак его исходного знака: 0 — плюс, 1 — минус;
;   RSI — текущая позиция в буфере числа;
;   RCX — длина уже подготовленной части строки, пока только символ LF.
.absolute_value_ready:
    mov r9, 10

; Последовательно извлекает десятичные цифры справа налево.
; Смысл регистров на каждом проходе:
;   RAX — ещё не преобразованная старшая часть числа;
;   R9  — основание системы счисления, то есть 10;
;   RDX — остаток от деления, то есть очередная цифра;
;   RSI — позиция, перед которой записывается следующая цифра;
;   RCX — текущая длина сформированной строки;
;   R8B — признак необходимости добавить знак минус.
.number_loop:
    ; Остаток от деления на 10 — очередная цифра, частное — ещё не обработанная
    ; старшая часть числа. Цикл выполняется хотя бы раз, поэтому ноль выводится.
    xor rdx, rdx
    div r9
    add dl, '0'
    dec rsi
    mov [rsi], dl
    inc rcx
    test rax, rax
    jnz .number_loop

    ; Для исходного отрицательного числа добавляем знак перед первой цифрой.
    test r8b, r8b
    jz .number_ready
    dec rsi
    mov byte [rsi], '-'
    inc rcx

; Выводит полностью сформированную строку с результатом.
; После прошлого блока RSI указывает на первый символ числа,
; а RCX хранит полную длину числа вместе со знаком и переводом строки.
.number_ready:
    ; RSI уже указывает на первый символ, RCX содержит длину вместе с LF.
    mov rdi, 1
    mov rdx, rcx
    call write_all
    jc .exit_error

    ; Код возврата 0 означает успешное завершение.
    xor rdi, rdi
    jmp .exit


; =============================================================================
; Обработка ошибок и завершение программы
; =============================================================================

; Закрывает файл после ошибки системного вызова read.
; На этом пути [file_descriptor] хранит дескриптор открытого файла;
; содержимое остальных регистров больше не используется.
.close_and_broken:
    ; При ошибке чтения закрываем уже открытый дескриптор перед выводом сообщения.
    mov rax, SYS_CLOSE
    mov rdi, [file_descriptor]
    syscall

; Выводит общее сообщение для ошибок файла, формата и переполнения.
; Из прошлых блоков здесь важны только сохранённые в памяти filename_ptr
; и filename_len; значения рабочих регистров намеренно не учитываются.
.broken:
    ; Ошибки открытия, чтения, формата данных и переполнения имеют единый вид:
    ; "<имя файла>: файл испорчен". Сообщение отправляется в stdout по условию
    ; исходной программы; возможную ошибку самого вывода здесь уже не обрабатываем.
    mov rdi, 1
    mov rsi, [filename_ptr]
    mov rdx, [filename_len]
    call write_all

    mov rdi, 1
    lea rsi, [broken_message]
    mov rdx, broken_len
    call write_all

; Подготавливает аварийный код завершения.
; Предыдущий блок мог оставить в регистрах аргументы write_all,
; поэтому здесь смысл имеет только заново установленный RDI — код возврата 1.
.exit_error:
    ; Любая ошибка завершается кодом 1.
    mov rdi, 1
    jmp .exit

; Обрабатывает запуск без единственного обязательного имени файла.
; После проверки argc содержимое рабочих регистров не требуется;
; блок сам задаёт RDI, RSI и RDX как аргументы вывода подсказки.
.usage:
    ; Некорректное число аргументов: подсказка выводится в stderr (fd = 2).
    mov rdi, 2
    lea rsi, [usage_message]
    mov rdx, usage_len
    call write_all
    mov rdi, 1

; Завершает процесс через системный вызов exit.
; После предыдущего блока RDI хранит смысловой код завершения:
; 0 — успех, 1 — ошибка.
.exit:
    ; exit(RDI), где RDI — заранее подготовленный код возврата.
    mov rax, SYS_EXIT
    syscall


; =============================================================================
; parse_line — разбор одной строки с целыми числами
; =============================================================================
;
; Вход:
;   RSI — адрес первого символа строки;
;   RDX — адрес конца строки, не включённого в диапазон.
;
; Выход при успехе:
;   RAX — сумма всех чисел;
;   RCX — количество чисел;
;   CF = 0.
;
; Выход при ошибке:
;   CF = 1; значения остальных регистров не определены.
;
; Допустимый формат элемента: пробелы/табуляции, необязательный знак + или -,
; одна или несколько цифр, пробелы/табуляции. Элементы разделяются запятыми.
; Пустые элементы, лишняя запятая, другие символы и переполнение int64 считаются
; ошибкой. Процедура использует R8–R14 как внутренние рабочие регистры.
parse_line:
    ; Инициализация состояния разбора.
    mov r8, rsi                 ; текущая позиция в строке
    mov r9, rdx                 ; конец строки, не включительно
    xor r10, r10                ; накопленная сумма
    xor r11, r11                ; количество разобранных чисел

; Начинает разбор очередного элемента массива.
; Смысл регистров:
;   R8  — адрес начала ещё не разобранной части строки;
;   R9  — неизменный адрес конца строки;
;   R10 — сумма уже разобранных чисел;
;   R11 — количество уже разобранных чисел.
.next_element:

; Пропускает пробелы и горизонтальные табуляции перед числом.
; R8 хранит адрес текущего символа, R9 — адрес конца строки;
; R10 и R11 продолжают хранить накопленную сумму и количество чисел.
; Если достигнут конец, элемент отсутствует: так обнаруживаются пустая строка
; и запятая без числа после неё.
.skip_leading_spaces:
    cmp r8, r9
    je .parse_error

    mov al, [r8]
    cmp al, ' '
    je .leading_space
    cmp al, 9
    jne .read_sign

; Сдвигает позицию разбора за один найденный начальный пробельный символ.
; После прошлого блока R8 указывает на этот пробел или табуляцию,
; а AL хранит код проверенного пробельного символа.
.leading_space:
    inc r8
    jmp .skip_leading_spaces

; Определяет знак очередного числа.
; После пропуска пробелов R8 указывает на первый непробельный символ,
; AL хранит этот символ, R10 — прежнюю сумму, R11 — прежнее количество.
; R12B получает смысл признака знака: 0 — плюс, 1 — минус.
.read_sign:
    xor r12d, r12d
    cmp al, '-'
    jne .check_plus

    mov r12b, 1
    inc r8
    jmp .digits_start

; Проверяет необязательный знак плюс.
; После прошлого блока R8 всё ещё указывает на первый символ числа,
; AL хранит этот символ, а R12B уже означает неотрицательный знак.
.check_plus:
    cmp al, '+'
    jne .digits_start
    inc r8

; Проверяет наличие первой цифры и начинает формирование модуля числа.
; Смысл регистров:
;   R8   — адрес первой цифры после необязательного знака;
;   R9   — адрес конца строки;
;   R12B — знак текущего числа;
;   R13  — после проверки будет хранить накапливаемый модуль числа.
.digits_start:
    ; Сразу после необязательного знака должна находиться хотя бы одна цифра.
    cmp r8, r9
    je .parse_error

    mov al, [r8]
    cmp al, '0'
    jb .parse_error
    cmp al, '9'
    ja .parse_error

    ; Модуль числа накапливается как беззнаковое значение. Это необходимо для
    ; корректного представления -9223372036854775808, модуль которого равен 2^63.
    xor r13, r13

; Читает цифры и постепенно собирает из них целое число.
; Смысл регистров на каждом проходе:
;   R8   — адрес текущего символа;
;   R9   — адрес конца строки;
;   R12B — знак разбираемого числа;
;   R13  — модуль, накопленный из предыдущих цифр;
;   RAX  — код текущей цифры, затем её числовое значение от 0 до 9.
.digit_loop:
    ; Конец диапазона или первый нецифровой символ завершает чтение числа.
    cmp r8, r9
    je .digits_ready

    movzx rax, byte [r8]
    cmp al, '0'
    jb .digits_ready
    cmp al, '9'
    ja .digits_ready
    sub eax, '0'

    ; До операции value = value * 10 + digit проверяем границы int64.
    ; Первые 18 цифр сравниваются с INT64_MAX / 10. Если частичное значение
    ; совпало с этой границей, последняя цифра может быть не больше 7 для плюса
    ; и не больше 8 для минуса.
    mov r14, 922337203685477580
    cmp r13, r14
    ja .parse_error
    jb .append_digit

    test r12b, r12b
    jz .positive_last_digit
    cmp eax, 8
    ja .parse_error
    jmp .append_digit

; Проверяет последнюю допустимую цифру положительного int64.
; После прошлого блока R13 хранит предельный префикс 922337203685477580,
; EAX — добавляемую цифру, R12B — признак положительного числа.
.positive_last_digit:
    cmp eax, 7
    ja .parse_error

; Добавляет проверенную цифру к модулю текущего числа.
; R13 хранит ранее собранный модуль, RAX — новую цифру,
; R8 указывает на символ этой цифры и после добавления сдвигается дальше.
.append_digit:
    imul r13, r13, 10
    add r13, rax
    inc r8
    jmp .digit_loop

; Применяет знак после того, как все цифры текущего числа прочитаны.
; После прошлого блока R13 хранит полный беззнаковый модуль числа,
; R12B — его знак, R8 — адрес первого символа после числа.
.digits_ready:
    ; Применяем сохранённый знак к готовому модулю.
    mov rax, r13
    test r12b, r12b
    jz .value_ready
    neg rax

; Добавляет готовое знаковое число к результатам разбора строки.
; Смысл регистров:
;   RAX — полностью сформированное текущее число со знаком;
;   R10 — сумма предыдущих чисел;
;   R11 — количество предыдущих чисел;
;   R8  — адрес символа сразу после текущего числа.
.value_ready:
    ; Добавляем число к общей сумме. Даже если каждое число помещается в int64,
    ; их сумма может переполниться, поэтому проверяется флаг OF.
    add r10, rax
    jo .parse_error
    inc r11

; Пропускает пробелы и горизонтальные табуляции после числа.
; После прошлого блока R10 хранит обновлённую сумму, R11 — обновлённое
; количество чисел, R8 — адрес следующего ещё не проверенного символа.
.skip_trailing_spaces:
    cmp r8, r9
    je .parse_success

    mov al, [r8]
    cmp al, ' '
    je .trailing_space
    cmp al, 9
    jne .expect_comma

; Сдвигает позицию разбора за один конечный пробельный символ.
; R8 указывает на найденный пробел или табуляцию, AL хранит его код;
; R10 и R11 сохраняют результаты разбора уже принятой части строки.
.trailing_space:
    inc r8
    jmp .skip_trailing_spaces

; Требует запятую между двумя соседними элементами массива.
; После прошлого блока R8 указывает на первый непробельный символ после числа,
; AL хранит этот символ, R10 — сумму, R11 — количество принятых чисел.
.expect_comma:
    cmp al, ','
    jne .parse_error
    inc r8
    jmp .next_element

; Возвращает вызывающему коду успешный результат разбора.
; После прошлого блока R10 хранит сумму всей строки,
; R11 — количество всех чисел, R8 совпадает с адресом конца строки.
.parse_success:
    ; Возвращаем накопленные значения и сбрасываем флаг переноса.
    mov rax, r10
    mov rcx, r11
    clc
    ret

; Возвращает признак ошибки формата или арифметического переполнения.
; Поскольку переход сюда возможен из разных проверок, значения рабочих
; регистров не имеют общего смысла и вызывающий код не должен их использовать.
.parse_error:
    ; Установленный CF сообщает вызывающему коду о некорректной строке.
    stc
    ret


; =============================================================================
; write_all — гарантированная запись всего переданного диапазона
; =============================================================================
;
; Вход:
;   RDI — файловый дескриптор;
;   RSI — адрес первого выводимого байта;
;   RDX — количество байтов.
;
; Выход:
;   CF = 0, если записан весь диапазон;
;   CF = 1 при ошибке записи.
;
; Системный вызов write может записать только часть данных, поэтому процедура
; повторяет его, сдвигая адрес и уменьшая остаток, пока не запишет всё.
write_all:
    ; Пустой диапазон уже считается успешно записанным.
    test rdx, rdx
    jz .write_success

; Повторяет write, пока весь диапазон не будет выведен.
; Смысл регистров на каждом проходе:
;   RDI — файловый дескриптор назначения;
;   RSI — адрес начала ещё не записанной части;
;   RDX — длина ещё не записанной части;
;   RAX — после syscall количество байтов, записанных за один вызов.
.write_loop:
    mov rax, SYS_WRITE
    syscall

    ; Прерванный сигналом write безопасно повторяется с теми же аргументами.
    cmp rax, -4                 ; EINTR
    je .write_loop

    ; Отрицательное значение — ошибка. Ноль при ненулевой длине не продвигает
    ; запись и привёл бы к бесконечному циклу, поэтому тоже считается ошибкой.
    test rax, rax
    jle .write_error

    ; RAX байтов уже записаны: переходим к ещё не выведенной части диапазона.
    add rsi, rax
    sub rdx, rax
    jnz .write_loop

; Сообщает вызывающему коду об успешной записи.
; После прошлого блока RDX означает, что незаписанных байтов не осталось;
; остальные изменённые процедурой регистры вызывающий код не сохраняет.
.write_success:
    clc
    ret

; Сообщает вызывающему коду об ошибке системного вызова write.
; RAX хранит код ошибки или нулевой результат записи;
; содержимое остальных рабочих регистров для вызывающего кода несущественно.
.write_error:
    stc
    ret
